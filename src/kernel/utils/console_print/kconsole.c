void fb_draw_bitmap(uint32_t start_x, uint32_t start_y, const unsigned char *bitmap, uint32_t width, uint32_t height) {
    for (uint32_t y = 0; y < height; y++) {
        for (uint32_t x = 0; x < width; x++) {
            uint32_t img_offset = (y * width + x) * 3; // Assuming 24-bit RGB
            
            uint8_t r = bitmap[img_offset];
            uint8_t g = bitmap[img_offset + 1];
            uint8_t b = bitmap[img_offset + 2];
            
            uint32_t color = (r << 16) | (g << 8) | b;
            fb_put_pixel(start_x + x, start_y + y, color);
        }
    }
}

static void fb_draw_cursor(bool visible) {
    uint32_t color = visible ? fg_color : bg_color;
    for (int cy = 14; cy < 16; cy++) {
        for (int cx = 0; cx < 8; cx++) {
            fb_put_pixel(cursor_x + cx, cursor_y + cy, color);
        }
    }
}

static void fb_scroll() {
    if (!fb) return;
    fb_draw_cursor(false);
    
    uint32_t scroll_bytes = fb_pitch * 16;
    uint32_t total_bytes = fb_pitch * fb_height;
    
    uint8_t *dest = fb;
    uint8_t *src = fb + scroll_bytes;
    uint32_t bytes_to_move = total_bytes - scroll_bytes;
    
    for (uint32_t i = 0; i < bytes_to_move; i++) {
        dest[i] = src[i];
    }
    
    for (uint32_t i = 0; i < scroll_bytes; i++) {
        dest[bytes_to_move + i] = 0;
    }
    cursor_y -= 16;
    fb_draw_cursor(cursor_is_visible);
}

void kput_char(char c) {
    fb_draw_cursor(false);

    if (c == '\n') {
        cursor_x = 0;
        cursor_y += 16;
    } else if (c == '\r') {
        cursor_x = 0;
    } else if (c == '\b') {
        kbackspace();
        return;
    } else if (c >= 32 && c <= 126) {
        const uint8_t *glyph = font8x16[(uint8_t)c];
        for (int cy = 0; cy < 16; cy++) {
            uint8_t row = glyph[cy];
            for (int cx = 0; cx < 8; cx++) {
                if (row & (0x80 >> cx)) {
                    fb_put_pixel(cursor_x + cx, cursor_y + cy, fg_color);
                } else {
                    fb_put_pixel(cursor_x + cx, cursor_y + cy, bg_color);
                }
            }
        }
        cursor_x += 8;
        if (cursor_x >= fb_width) {
            cursor_x = 0;
            cursor_y += 16;
        }
    }
    
    if (cursor_y + 16 > fb_height) {
        fb_scroll();
    }
    
    cursor_is_visible = true;
    cursor_blink_counter = 0;
    fb_draw_cursor(true);
}

void kprint(const char *c) {
  while (*c) {
      kput_char(*c++);
  }
}

void kprintln(const char *c) {
  kprint(c);
  kput_char('\n');
}

void kclear_screen(void) {
  if (!fb) return;
  uint32_t total_bytes = fb_pitch * fb_height;
  for (uint32_t i = 0; i < total_bytes; i++) {
      fb[i] = 0;
  }
  cursor_x = 0;
  cursor_y = 0;
  cursor_is_visible = true;
  cursor_blink_counter = 0;
  fb_draw_cursor(true);
}

void kscreen_initialize() {
  vbe_mode_info_t* vbe_info = (vbe_mode_info_t*)0x8000;
  fb = (uint8_t*)vbe_info->framebuffer;
  fb_width = vbe_info->width;
  fb_height = vbe_info->height;
  fb_pitch = vbe_info->pitch;
  fb_bpp = vbe_info->bpp;

  kclear_screen();
  log_info(MODULE, "Initialized Graphical Console");
}

void kscreen_timer_tick(void) {
  cursor_blink_counter++;
  if (cursor_blink_counter >= 500) {
      cursor_blink_counter = 0;
      cursor_is_visible = !cursor_is_visible;
      fb_draw_cursor(cursor_is_visible);
  }
}

void kbackspace() {
  fb_draw_cursor(false);

  if (cursor_x >= 8) {
      cursor_x -= 8;
  } else if (cursor_y >= 16) {
      cursor_y -= 16;
      cursor_x = fb_width - 8;
  }

  for (int cy = 0; cy < 16; cy++) {
      for (int cx = 0; cx < 8; cx++) {
          fb_put_pixel(cursor_x + cx, cursor_y + cy, bg_color);
      }
  }

  fb_draw_cursor(cursor_is_visible);
}

size_t kconsole_read_line(char *buffer, size_t size) {
  if (buffer == NULL || size == 0) {
    return 0;
  }

  vfs_node_t *stdin = vfs_find("stdin");
  if (!stdin) {
    log_error(MODULE, "FAILED: stdin not found in VFS");
    return 0;
  }

  size_t index = 0;
  char c;

  while (index < size - 1) {
    if (vfs_read(stdin, 0, 1, (uint8_t *)&c)) {
      if (c == '\n' || c == '\r') {
        kput_char('\n');
        buffer[index] = '\0';
        return index;
      } else if (c == '\b' || c == 0x7F) {
        if (index > 0) {
          index--;
          kbackspace();
        }
      } else if ((c >= 0x20 && c <= 0x7E)) {
        buffer[index] = c;
        kput_char(c);
        index++;
      }
    }
  }

  buffer[index] = '\0';
  return index;
}

void fb_draw_bmp_file(const char *filename, uint32_t start_x, uint32_t start_y) {
vfs_node_t *node = vfs_open(filename);
    if (!node) {
        node = fat16_vfs_open(filename);
    }
    if (!node) {
        log_debug(MODULE, "BMP file not found: %s", filename);
        return;
    }

    bmp_file_header_t file_header;
    bmp_info_header_t info_header;

    if (vfs_read(node, 0, sizeof(bmp_file_header_t), (uint8_t*)&file_header) != sizeof(bmp_file_header_t) ||
        file_header.file_type != 0x4D42) {
        log_error(MODULE, "Invalid BMP file header: %s", filename);
        vfs_close(node);
        return;
    }

    vfs_read(node, sizeof(bmp_file_header_t), sizeof(bmp_info_header_t), (uint8_t*)&info_header);

    int32_t width = info_header.width;
    int32_t height = info_header.height;
    if (info_header.bpp != 24 && info_header.bpp != 32) {
        log_error(MODULE, "Unsupported BMP bpp: %u (requires 24 or 32)", info_header.bpp);
        vfs_close(node);
        return;
    }

    bool top_to_bottom = (height < 0);
    if (top_to_bottom) height = -height;

    uint32_t bytes_per_pixel = info_header.bpp / 8;
    uint32_t row_stride = (width * bytes_per_pixel + 3) & ~3;
    
    uint8_t *row_buffer = kmem_zalloc(row_stride);
    if (!row_buffer) {
        log_error(MODULE, "Failed to allocate memory for BMP row buffer");
        vfs_close(node);
        return;
    }

    uint32_t current_offset = file_header.data_offset;

    for (int32_t y = 0; y < height; y++) {
        int32_t target_y = top_to_bottom ? (start_y + y) : (start_y + height - 1 - y);
        
        vfs_read(node, current_offset, row_stride, row_buffer);
        current_offset += row_stride;

        for (int32_t x = 0; x < width; x++) {
            uint32_t pixel_offset = x * bytes_per_pixel;
            uint8_t b = row_buffer[pixel_offset];
            uint8_t g = row_buffer[pixel_offset + 1];
            uint8_t r = row_buffer[pixel_offset + 2];

            uint32_t color = (r << 16) | (g << 8) | b;
            fb_put_pixel(start_x + x, target_y, color);
        }
    }

    kmem_free(row_buffer);
    vfs_close(node);
}